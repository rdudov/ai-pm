#!/usr/bin/env python3
"""Одни правила языка для всего, что продакт пишет пользователю.

Пользователь сказал 23 августа 2026: «мне реально сложно читать, что ты
пишешь… я трачу больше времени и быстрее устаю, читая твои отчёты и ответы».
Он назвал отчёты и ответы, то есть весь текст, который получает от продакта, а
не одно фоновое письмо. Правила поэтому живут здесь, а все три пути к
пользователю берут их отсюда: контракт письма `thread_tick.verdict_block()`,
утренняя оперативка `daily_standup.prompt()` и стартовый промпт консольной
сессии `claude_product_owner.STARTUP_PROMPT`. AGENTS.md называет то же правило
словами, но приказ, которого нет в промпте, модель не выполняет — это уже
проверено письмом 23 августа 07:20 UTC.
"""

from __future__ import annotations

import textwrap

# Одно предложение — одно требование, чтобы в промпте не пропало ни одного.
RULES = """пиши простым инженерным русским. Подлежащее, сказуемое, прямой
порядок слов. Активный залог: «продакт удалил», а не «деревья удалены». Одно
утверждение в предложении. Предложение — не длиннее примерно двадцати слов,
абзац — не длиннее четырёх предложений. Не пиши вводных оборотов и книжных
формул («по слову пользователя», «наблюдённый повод», «этим не отменяется»,
«не бывает»). Не ставь сказуемое в конец. Не заменяй глагол отглагольным
существительным: пиши «мы не доставили», а не «доставка не закрыта». Не
подменяй причину метафорой: «дверь», «стена», «закапывает»."""

# Повод правила словами пользователя. Точку в конце ставит тот, кто вставляет
# правила: в списке письма пункты разделены точкой с запятой.
REASON = ("Пользователь сказал 23 августа: «мне реально сложно читать, что ты "
          "пишешь… я трачу больше времени и быстрее устаю»")


def _one_paragraph(text: str) -> str:
    """Собственные переносы исходника не должны попадать в чужую разметку."""
    return " ".join(text.split())


def as_bullet() -> str:
    """Пункт для списка правил: первая строка без отступа, следующие с двумя."""
    return textwrap.fill(
        _one_paragraph(f"{RULES} {REASON}"), width=78,
        initial_indent="- ", subsequent_indent="  ",
    )


def console_rules() -> str:
    """Те же правила для консольного ответа и отчёта, без списка."""
    return _one_paragraph(
        "Всякий твой текст для пользователя — консольный ответ, отчёт, "
        f"письмо — подчиняется одним правилам языка: {RULES} {REASON}."
    )

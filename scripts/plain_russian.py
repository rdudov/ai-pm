#!/usr/bin/env python3
"""Одни правила языка для всего, что продакт пишет пользователю.

Пользователь сказал 23 августа 2026: «мне реально сложно читать, что ты
пишешь… я трачу больше времени и быстрее устаю, читая твои отчёты и ответы».
Он назвал отчёты и ответы, то есть весь текст, который получает от продакта, а
не одно фоновое письмо. AGENTS.md называет то же правило словами, но приказ,
которого нет в промпте, модель не выполняет — это уже проверено письмом
23 августа 07:20 UTC.

Список путей к пользователю закрытым не бывает: ответ на входящее письмо и
ответ на просьбу из разговора собираются вообще не здесь, а в почтовой двери
соседнего репозитория, и перечислить их тут значит через круг ошибиться снова.
Поэтому правила подключены не к списку промптов, а к одному месту, через
которое проходит каждый ход модели продакта, — `claude_product_owner`:
`--entry print` отдаёт их обеим машинам как системный приказ, а
`STARTUP_PROMPT` — интерактивной консоли. Три промпта, которые пишут текст
человеку сами (`thread_tick.verdict_block()`, `daily_standup.prompt()` и тот же
`STARTUP_PROMPT`), повторяют этот же текст внутри своего контракта, где он
стоит рядом с остальными правилами того же ответа.

Отсюда же следует, что здесь лежит каждое правило языка, а не одна грамматика.
Правило, оставленное в контракте одного письма, доходит до одного письма.
"""

from __future__ import annotations

import textwrap

# Одно предложение — одно требование, чтобы в промпте не пропало ни одного.
#
# Термин — тоже язык, и правило о нём стоит здесь, а не в контракте письма.
# До 24 августа 2026 «ни одного внутреннего термина без расшифровки» жило
# только в `thread_tick.verdict_block()`, то есть доходило до письма треда и
# оперативки, но не до ответа на входящее письмо и не до ответа на просьбу из
# разговора: их промпты собирает почтовая дверь соседнего репозитория, а отсюда
# они получают ровно этот текст. Проверка круга 11 прочла такой ответ и нашла в
# нём `lifecycle`, `drop` и `idle` без перевода — при нулевых нарушениях стиля,
# потому что стиль термина не измеряет.
RULES = """пиши простым инженерным русским. Подлежащее, сказуемое, прямой
порядок слов. Активный залог: «продакт удалил», а не «деревья удалены». Одно
утверждение в предложении. Предложение — не длиннее примерно двадцати слов,
абзац — не длиннее четырёх предложений. Не пиши вводных оборотов и книжных
формул («по слову пользователя», «наблюдённый повод», «этим не отменяется»,
«не бывает»). Не ставь сказуемое в конец. Не заменяй глагол отглагольным
существительным: пиши «мы не доставили», а не «доставка не закрыта». Не пиши
ни одного внутреннего термина без расшифровки при первом употреблении: слова
вроде кандидат, вердикт, ревью, lifecycle, controller, receipt, drop, idle,
GAP человеку ничего не говорят, поэтому скажи обычными словами, что это, и
только потом, если нужно, назови термин. Не подменяй причину метафорой
(«дверь», «стена», «закапывает»): причинно-следственную связь разворачивай
предложением с подлежащим и сказуемым."""

# Повод правила словами пользователя. Точку в конце ставит тот, кто вставляет
# правила: в списке письма пункты разделены точкой с запятой.
REASON = ("Пользователь сказал 23 августа: «мне реально сложно читать, что ты "
          "пишешь… я трачу больше времени и быстрее устаю»")


def _one_paragraph(text: str) -> str:
    """Собственные переносы исходника не должны попадать в чужую разметку."""
    return " ".join(text.split())


def as_bullet() -> str:
    """Пункт для списка правил: первая строка без отступа, следующие с двумя."""
    return textwrap.fill(
        _one_paragraph(f"{RULES} {REASON}"), width=78,
        initial_indent="- ", subsequent_indent="  ",
    )


def as_paragraph() -> str:
    """Те же правила одним абзацем: там, где списка правил нет.

    Так они уходят системным приказом каждому фоновому ходу продакта и
    стартовым промптом — интерактивной консоли.
    """
    return _one_paragraph(
        "Всякий твой текст для пользователя — консольный ответ, отчёт, "
        f"письмо — подчиняется одним правилам языка: {RULES} {REASON}."
    )
